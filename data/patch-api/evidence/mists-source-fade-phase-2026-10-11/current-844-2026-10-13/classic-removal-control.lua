local frame = CreateFrame("Frame")
local event = "SIM_CLASSIC_EVENT_REMOVAL_CONTROL"
local deliveries = 0
frame:SetScript("OnEvent", function(self, name)
    assert(self == frame and name == event)
    deliveries = deliveries + 1
end)
assert(select("#", frame:UnregisterEvent(event)) == 1)
assert(frame:UnregisterEvent(event) == false)
frame:RegisterEvent(event)
assert(frame:IsEventRegistered(event))
A_Admin.FireEvent(event)
assert(deliveries == 1)
assert(frame:UnregisterEvent(event) == true)
A_Admin.FireEvent(event)
assert(deliveries == 1)
assert(frame:UnregisterEvent(event) == false)
frame:RegisterUnitEvent(event, "player", "target")
A_Admin.FireEvent(event, "player")
A_Admin.FireEvent(event, "target")
A_Admin.FireEvent(event, "focus")
assert(deliveries == 3)
assert(frame:UnregisterEvent(event) == true)
A_Admin.FireEvent(event, "player")
A_Admin.FireEvent(event, "target")
assert(deliveries == 3)
assert(frame:UnregisterEvent(event) == false)
print("MISTS_CLASSIC_EVENT_REMOVAL_CONTROL_OK")
