-- Simulator contract diagnostic; no native playback/receiver parity claim.
local first = CreateFrame('MovieFrame', 'MovieArityFirst', UIParent)
local second = CreateFrame('MovieFrame', 'MovieAritySecond', UIParent)
assert(first:GetObjectType() == 'MovieFrame')
assert(second:GetObjectType() == 'MovieFrame')
first:Hide()
second:Hide()
local function check(label, movie, enabled)
    assert(select('#', movie:EnableSubtitles(enabled)) == 0)
    assert(not first:IsShown() and not second:IsShown())
    print('MOVIE_ARITY ' .. label .. ' 0')
end
check('first_true', first, true)
check('second_true', second, true)
check('first_false', first, false)
check('second_false', second, false)
local setter = first.EnableSubtitles
local ordinary = CreateFrame('Frame', 'MovieArityOrdinary', UIParent)
assert(not pcall(setter, ordinary, true))
print('MOVIE_RECEIVER Frame rejected')
assert(not pcall(setter, {}, true))
print('MOVIE_RECEIVER plain_table rejected')
assert(not first:IsShown() and not second:IsShown())
print('MOVIE_ARITY_DONE')
